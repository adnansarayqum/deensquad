import "server-only";
import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, rm, stat } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { DeleteObjectCommand, GetObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { Upload } from "@aws-sdk/lib-storage";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { isDemo } from "../db";

// Where pictures and videos live. In production: the club's private Railway bucket (S3-compatible), named by
// MEDIA_BUCKET, MEDIA_ENDPOINT, MEDIA_REGION, MEDIA_ACCESS_KEY_ID and MEDIA_SECRET_ACCESS_KEY, which Railway fills in
// as references to the bucket's own variables (so no key is ever copied). Elsewhere (dev, tests, the demo): a folder
// on disk, `MEDIA_DIR` or `.data/media`. In production without a bucket there's no store and uploads are refused.

export type MediaStore = {
  kind: "s3" | "disk";
  put(key: string, body: Uint8Array | Readable, mime: string): Promise<void>;
  remove(key: string): Promise<void>;
  /** S3: a short-lived link straight to the bucket (its traffic is free). Disk: null, the app serves the file itself. */
  signedUrl(key: string, mime: string, now?: Date): Promise<string | null>;
  /** Disk only: the file's path, for the app to serve with range requests. */
  path(key: string): string | null;
};

/** Object keys are generated by the app ("media/<uuid>.jpg"); anything else is refused before touching a store. */
export const KEY = /^media\/[0-9a-f-]{36}(-poster)?\.(jpg|mp4|mov|webm)$/;

function s3Config() {
  const e = process.env;
  const bucket = e.MEDIA_BUCKET?.trim();
  const endpoint = e.MEDIA_ENDPOINT?.trim();
  const accessKeyId = e.MEDIA_ACCESS_KEY_ID?.trim();
  const secretAccessKey = e.MEDIA_SECRET_ACCESS_KEY?.trim();
  if (!bucket || !endpoint || !accessKeyId || !secretAccessKey) return null;
  return {
    bucket,
    client: new S3Client({
      endpoint,
      region: e.MEDIA_REGION?.trim() || "auto",
      credentials: { accessKeyId, secretAccessKey },
      // Railway's buckets use virtual-hosted URLs; older ones say path style on their Credentials tab.
      forcePathStyle: e.MEDIA_PATH_STYLE === "1",
    }),
  };
}

/** Links stay valid for 2 hours from the start of the hour they were made in, so within an hour every page view asks
 * for the same address and the browser's copy is used (a fresh signature each time would re-download every picture). */
export const SIGN_WINDOW_SECONDS = 3600;
export function signingWindow(now: Date): Date {
  return new Date(Math.floor(now.getTime() / (SIGN_WINDOW_SECONDS * 1000)) * SIGN_WINDOW_SECONDS * 1000);
}

function s3Store(bucket: string, client: S3Client): MediaStore {
  return {
    kind: "s3",
    async put(key, body, mime) {
      await new Upload({ client, params: { Bucket: bucket, Key: key, Body: body, ContentType: mime }, partSize: 8 * 1024 * 1024, queueSize: 2 }).done();
    },
    async remove(key) {
      await client.send(new DeleteObjectCommand({ Bucket: bucket, Key: key }));
    },
    async signedUrl(key, mime, now = new Date()) {
      return getSignedUrl(
        client,
        new GetObjectCommand({ Bucket: bucket, Key: key, ResponseContentType: mime, ResponseCacheControl: "private, max-age=3600" }),
        { expiresIn: 2 * SIGN_WINDOW_SECONDS, signingDate: signingWindow(now) },
      );
    },
    path: () => null,
  };
}

function diskStore(root: string): MediaStore {
  const full = (key: string) => {
    if (!KEY.test(key)) throw new Error("bad media key");
    return join(root, key);
  };
  return {
    kind: "disk",
    async put(key, body) {
      const file = full(key);
      await mkdir(dirname(file), { recursive: true });
      await pipeline(body instanceof Uint8Array ? Readable.from([body]) : body, createWriteStream(file));
    },
    async remove(key) {
      await rm(full(key), { force: true });
    },
    signedUrl: async () => null,
    path: (key) => full(key),
  };
}

let cached: MediaStore | null | undefined;

/** The store for this server, or null when pictures and videos aren't set up (production without a bucket). */
export function mediaStore(): MediaStore | null {
  if (cached !== undefined) return cached;
  const s3 = s3Config();
  if (s3) cached = s3Store(s3.bucket, s3.client);
  else if (process.env.MEDIA_DIR?.trim()) cached = diskStore(resolve(process.env.MEDIA_DIR.trim()));
  else if (process.env.NODE_ENV !== "production" || isDemo()) cached = diskStore(resolve(".data/media"));
  else cached = null;
  return cached;
}

/** Tests: use this folder (or a store) instead. */
export function setMediaStoreForTests(store: MediaStore | string | null): void {
  cached = typeof store === "string" ? diskStore(store) : store;
}

export async function fileSize(path: string): Promise<number | null> {
  try {
    return (await stat(path)).size;
  } catch {
    return null;
  }
}

export { createReadStream };
